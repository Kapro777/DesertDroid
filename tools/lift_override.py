#!/usr/bin/env python3
"""lift_override.py <exe> <catalog.json> <names.json> <out_prefix> <seed:end> [<seed:end>...]

Lifta funcoes por VA (mesmo fora das fronteiras do catalogo — casos onde o
recursive descent fundiu/marcou mal o comeco verdadeiro) e grava um arquivo
C por seed no diretorio de gen do build: recomp_override_<seed>.c.

Cada arquivo: a funcao sub_<VA> + o registro dd_override_register_<VA>()
que liga o VA na tabela de overrides do DesertDroid (recomp_lookup_manual).

O C gerado e derivado do jogo: NUNCA commitado (fica no runner, gitignored).
Usado para: __scrt_common_main_seh real (0xECB75D) e WinMain (0x869C50),
cujos comecos verdadeiros nao sao fronteiras do catalogo.
"""
import sys, os, json

HERE = os.path.dirname(os.path.abspath(__file__))
PCRECOMP = os.environ.get(
    "PCRECOMP", os.path.normpath(os.path.join(HERE, "..", "..", "external", "pcrecomp")))
for sub in ("pe", "disasm", "lift"):
    sys.path.insert(0, os.path.join(PCRECOMP, "tools", sub))

from capstone import Cs, CS_ARCH_X86, CS_MODE_32  # noqa: E402
from pe_analyze import analyze_pe, build_iat_map   # noqa: E402
import disasm32                                     # noqa: E402
from lift32 import Lifter                          # noqa: E402


def lift_one(exe, cat, names, seed, end, out):
    info = analyze_pe(exe)
    iat = build_iat_map(info)
    data = open(exe, "rb").read()
    lifted = {fd["address"] for fd in cat["functions"]}
    dis = disasm32.Disassembler(data, info.image_base, info.sections)
    # descent DIRETO da funcao (sem find_functions: o cascade de discovery
    # la fora cobre o seed como interior de outra funcao e o dropa)
    f = dis.disassemble_function(seed, iat)
    if not (f and f.blocks):
        print(f"[override] disassemble_function falhou em {seed:#x}")
        return 1
    # The pinned pcrecomp Lifter has no hook_sites option; hook injection
    # is handled by the native runtime, not by the x86-to-C lifting API.
    lifter = Lifter(iat_map=iat, func_names=names, lifted=lifted,
                    precise_carry=True)
    code = lifter.lift_function(f)
    with open(out, "w", newline="\n") as fh:
        fh.write(f"/* AUTO-GENERATED by lift_override.py from {os.path.basename(exe)}. DO NOT EDIT, DO NOT COMMIT. */\n")
        fh.write('#define RECOMP_GENERATED_CODE\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n#include <math.h>\n#include <string.h>\n')
        fh.write("extern void dd_overrides_add(uint32_t va, recomp_func_t fn);\n\n")
        fh.write(code)
        fh.write(f"\nvoid dd_override_register_{seed:08X}(void);\n")
        fh.write(f"void dd_override_register_{seed:08X}(void) {{"
                 f" dd_overrides_add(0x{seed:08X}u, sub_{seed:08X}); }}\n")
    print(f"[override] sub_{seed:08X}..{f.end:08X} ({len(f.blocks)} blocos) -> {out}")
    if f.end >= end:
        print(f"[override] ATENCAO: funcao tocou o fim do range {end:#x} — aumentar range")
    return 0


def main():
    exe = sys.argv[1]
    cat = json.load(open(sys.argv[2]))
    names = {}
    if os.path.exists(sys.argv[3]):
        names = {int(k, 16): v for k, v in json.load(open(sys.argv[3])).items()}
    outdir = sys.argv[4]
    os.makedirs(outdir, exist_ok=True)
    rc = 0
    for spec in sys.argv[5:]:
        seed, end = (int(x, 0) for x in spec.split(":"))
        rc |= lift_one(exe, cat, names, seed, end,
                       os.path.join(outdir, f"recomp_override_{seed:08X}.c"))
    return rc


if __name__ == "__main__":
    sys.exit(main())
